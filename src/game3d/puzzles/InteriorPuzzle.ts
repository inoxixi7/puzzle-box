import * as THREE from "three";
import { gsap } from "gsap";

import { createPrizeGem, createToken } from "./finale";
import { aluminum, disposeTree, graphite, pickObject, screenCenter } from "./puzzleUtils";
import { PALETTE, css } from "../palette";

type InteriorPuzzleOptions = {
  // Box-local group; the puzzle uses box coordinates directly.
  parent: THREE.Object3D;
  // Top of the false floor.
  floorY: number;
  // The rack hangs on the lid's underside: the lid pivot, and the point on
  // the underside (pivot-local) where the rack's centre goes.
  lid: THREE.Object3D;
  rackAt: THREE.Vector3;
  canvas: HTMLCanvasElement;
  camera: THREE.Camera;
  onSolved?: () => void;
  // The key token, hovering over the open box, was tapped and taken.
  onTokenTaken?: () => void;
};

type Vec = [number, number];
type Size = "S" | "M" | "L";
type FixedId = "D" | "L1" | "L2";

// Pitch radii. Two gears mesh when their centres are r1 + r2 apart.
const SIZE: Record<Size, number> = { S: 0.33, M: 0.46, L: 0.6 };
// Loose gears on the rack, matching RACK_SLOTS.
const LOOSE: Size[] = ["L", "M", "M", "S", "S", "S"];
const FIXED: Record<FixedId, { at: Vec; r: number }> = {
  D: { at: [2.1, -0.3], r: 0.65 },
  L1: { at: [-0.8, -0.95], r: 0.4 },
  L2: { at: [-0.8, 1.0], r: 0.4 },
};
// Box x, z. Generated by a search that tries every way to put the loose
// gears on the pegs: exactly one opens both latches (S on 7 and 5, M on 3
// and 4: D–S–S–M, then that M turns L2 and, through the other M, L1). The L
// and one S are spares. Other fits turn a latch the wrong way or jam.
const PEGS: Vec[] = [
  [1.2753, -0.8295],
  [0.5483, -0.2495],
  [0.0303, -1.1742],
  [-0.0152, 0.6483],
  [-0.505, -0.1305],
  [0.7748, 0.6525],
  [0.1864, 1.4121],
  [1.3115, 0.282],
  [1.913, 0.7941],
  [1.2033, 1.1411],
];
const CASE = { x0: -2.6, x1: -1.4, z0: -0.6, z1: 0.6, height: 0.9 };
// Inside walls, less a margin.
const BOUNDS = { x: 2.77, z: 1.97 };
const MESH_TOL = 0.02;
// Closer than this without meshing, the teeth would collide.
const CLEARANCE = 0.12;

// rotation.y sign that opens each latch: L1 counter-clockwise seen from
// above, L2 clockwise.
const LATCHES: { id: "L1" | "L2"; open: number }[] = [
  { id: "L1", open: 1 },
  { id: "L2", open: -1 },
];
// Both must be past this in the same turn; each springs back on release.
const LATCH_OPEN = Math.PI / 2;
// Turned the wrong way a latch gives a little, then hits its stop.
const LATCH_STOP = -0.3;
const BOLT_TRAVEL = 0.25;

// 1: mesh, -1: clash, 0: apart.
function contact(a: Vec, ra: number, b: Vec, rb: number) {
  const d = Math.hypot(a[0] - b[0], a[1] - b[1]);
  const sum = ra + rb;
  if (Math.abs(d - sum) <= MESH_TOL) return 1;
  return d < sum + CLEARANCE ? -1 : 0;
}

// Fits on this peg against the walls, the case and the fixed gears.
function fitsBox([x, z]: Vec, r: number) {
  if (Math.abs(x) + r + 0.06 > BOUNDS.x || Math.abs(z) + r + 0.06 > BOUNDS.z) return false;
  const dx = Math.max(CASE.x0 - x, 0, x - CASE.x1);
  const dz = Math.max(CASE.z0 - z, 0, z - CASE.z1);
  if (Math.hypot(dx, dz) < r + 0.1) return false;
  return Object.values(FIXED).every((f) => contact([x, z], r, f.at, f.r) !== -1);
}

const GEAR_THICKNESS = 0.12;
const GEAR_LIFT = 0.08;

function gearGeometry(radius: number) {
  const teeth = Math.round(radius * 26);
  const root = radius - 0.05;
  const tip = radius + 0.06;
  const shape = new THREE.Shape();
  for (let i = 0; i < teeth; i++) {
    const a = (i / teeth) * Math.PI * 2;
    const step = (Math.PI * 2) / teeth;
    const points: [number, number][] = [
      [root, a],
      [tip, a + step * 0.2],
      [tip, a + step * 0.45],
      [root, a + step * 0.65],
    ];
    for (const [r, t] of points) {
      const x = Math.cos(t) * r;
      const y = Math.sin(t) * r;
      if (i === 0 && r === root && t === a) shape.moveTo(x, y);
      else shape.lineTo(x, y);
    }
  }
  shape.closePath();
  const hole = new THREE.Path();
  hole.absarc(0, 0, 0.07, 0, Math.PI * 2, true);
  shape.holes.push(hole);

  const geometry = new THREE.ExtrudeGeometry(shape, {
    depth: GEAR_THICKNESS,
    bevelEnabled: false,
    curveSegments: 6,
  });
  // Lie flat, bottom at y = 0. Shape angles keep their sense seen from above.
  geometry.rotateX(-Math.PI / 2);
  return geometry;
}

// Flat arc arrow lying on top of a gear. `sweep` > 0 runs counter-clockwise
// seen from above.
function arcArrow(radius: number, start: number, sweep: number, material: THREE.Material) {
  const group = new THREE.Group();
  const from = Math.min(start, start + sweep);
  const arc = new THREE.Mesh(
    new THREE.RingGeometry(radius - 0.025, radius + 0.025, 48, 1, from, Math.abs(sweep)),
    material,
  );
  group.add(arc);

  const end = start + sweep;
  const head = new THREE.Shape();
  head.moveTo(0.12, 0);
  head.lineTo(-0.03, 0.08);
  head.lineTo(-0.03, -0.08);
  head.closePath();
  const headMesh = new THREE.Mesh(new THREE.ShapeGeometry(head), material);
  headMesh.position.set(Math.cos(end) * radius, Math.sin(end) * radius, 0);
  headMesh.rotation.z = end + Math.sign(sweep) * (Math.PI / 2);
  group.add(headMesh);

  // Shape space (x, y) → box (x, -z): seen from above it reads the same.
  group.rotation.x = -Math.PI / 2;
  return group;
}

type Gear = { spinner: THREE.Group; body: THREE.Mesh };
type Loose = Gear & {
  size: Size;
  material: THREE.MeshStandardMaterial;
  slot: THREE.Vector3;
  peg: number | null;
  moving: boolean;
};

// Rack x, z: big gears in the back row, small ones staggered in front.
const RACK_SLOTS: Vec[] = [
  [-1.45, -0.33],
  [0, -0.33],
  [1.3, -0.33],
  [-0.6, 0.58],
  [0.65, 0.58],
  [1.95, 0.58],
];

// Act 3: pegs on the floor and loose gears on a rack. Tap a gear to take it,
// tap a peg to fit it; tap a fitted gear to put it back. Drag the driver (a
// pawl lets it turn only clockwise). Gears mesh only when their sizes span
// the gap between pegs; each mesh reverses the turn, and a ring of three
// jams. Both latches must turn open in the same drag.
export class InteriorPuzzle {
  private options: InteriorPuzzleOptions;
  private canvas: HTMLCanvasElement;
  private camera: THREE.Camera;

  private root = new THREE.Group();
  private rack = new THREE.Group();
  private fixed = {} as Record<FixedId, Gear>;
  private loose: Loose[] = [];
  private pegHits: THREE.Mesh[] = [];
  private held: Loose | null = null;
  private bolts = {} as Record<"L1" | "L2", { mesh: THREE.Mesh; rest: THREE.Vector3; out: THREE.Vector3 }>;
  private progress = { L1: 0, L2: 0 };
  private caseLid = new THREE.Group();
  private token: THREE.Group;
  private tokenGlow: THREE.MeshStandardMaterial;
  private prize: THREE.Group;
  private sparkles: THREE.Sprite[];
  private prizeLight = new THREE.PointLight(0xfff4e0, 0, 7, 2);
  private tokenLight = new THREE.PointLight(PALETTE.tokenBlue, 0, 6, 2);
  private halo: THREE.Sprite;
  // Larger invisible target: the token itself is small on screen.
  private tokenHit: THREE.Mesh;
  private tokenHover: gsap.core.Tween[] = [];
  private tokenReady = false;

  private enabled = false;
  private solved = false;
  private atStop = false;
  private jammed = false;
  private dragId: number | null = null;
  private lastAngle = 0;

  constructor(options: InteriorPuzzleOptions) {
    this.options = options;
    this.canvas = options.canvas;
    this.camera = options.camera;

    this.root.name = "interior-puzzle";
    this.root.position.y = options.floorY;
    options.parent.add(this.root);

    const metal = aluminum();
    const dark = graphite();
    const engraving = new THREE.MeshBasicMaterial({ color: 0x1c1d20, side: THREE.DoubleSide });
    const amber = new THREE.MeshBasicMaterial({ color: PALETTE.amber, side: THREE.DoubleSide });

    const makeGear = (radius: number, material: THREE.Material): Gear => {
      const spinner = new THREE.Group();
      const body = new THREE.Mesh(gearGeometry(radius), material);
      body.castShadow = true;
      body.receiveShadow = true;
      spinner.add(body);
      return { spinner, body };
    };
    const topArrow = (gear: THREE.Group, radius: number, start: number, sweep: number, material: THREE.Material) => {
      const arrow = arcArrow(radius, start, sweep, material);
      arrow.position.y = GEAR_THICKNESS + 0.002;
      gear.add(arrow);
    };
    const spacer = (x: number, z: number, radius: number) => {
      const mesh = new THREE.Mesh(new THREE.CylinderGeometry(radius, radius, GEAR_LIFT, 20), dark);
      mesh.position.set(x, GEAR_LIFT / 2, z);
      this.root.add(mesh);
    };

    for (const id of Object.keys(FIXED) as FixedId[]) {
      const { at, r } = FIXED[id];
      const gear = makeGear(r, id === "D" ? metal : dark);
      gear.spinner.position.set(at[0], GEAR_LIFT, at[1]);
      this.root.add(gear.spinner);
      spacer(at[0], at[1], 0.12);
      this.fixed[id] = gear;
    }
    // Driver arrow, and the pawl that lets it turn only clockwise.
    topArrow(this.fixed.D.spinner, 0.4, Math.PI * 0.85, -Math.PI * 1.2, engraving);
    const pawl = new THREE.Mesh(new THREE.BoxGeometry(0.1, 0.1, 0.32), dark);
    pawl.position.set(FIXED.D.at[0] + FIXED.D.r + 0.12, GEAR_LIFT + GEAR_THICKNESS / 2, FIXED.D.at[1]);
    this.root.add(pawl);
    // Latches: an amber arrow the way each opens.
    for (const { id, open } of LATCHES) {
      topArrow(this.fixed[id].spinner, 0.25, open > 0 ? -Math.PI * 0.35 : Math.PI * 0.85, open * Math.PI * 1.2, amber);
    }

    // Pegs: a short post in a machined ring.
    for (const [x, z] of PEGS) {
      spacer(x, z, 0.07);
      const ring = new THREE.Mesh(new THREE.RingGeometry(0.13, 0.17, 32), metal);
      ring.rotation.x = -Math.PI / 2;
      ring.position.set(x, 0.005, z);
      this.root.add(ring);
      const hit = new THREE.Mesh(
        new THREE.CircleGeometry(0.3, 16),
        new THREE.MeshBasicMaterial({ transparent: true, opacity: 0, depthWrite: false }),
      );
      hit.rotation.x = -Math.PI / 2;
      hit.position.set(x, GEAR_LIFT, z);
      this.root.add(hit);
      this.pegHits.push(hit);
    }

    // Rack on the lid's underside, gears facing down into the closed box and
    // toward the player once the lid is open.
    this.rack.position.copy(options.rackAt);
    this.rack.rotation.x = Math.PI;
    options.lid.add(this.rack);
    const shelf = new THREE.Mesh(new THREE.BoxGeometry(4.6, 0.05, 1.9), dark);
    shelf.position.y = -0.025;
    shelf.receiveShadow = true;
    this.rack.add(shelf);
    LOOSE.forEach((size, i) => {
      const material = metal.clone();
      const gear = makeGear(SIZE[size], material);
      const slot = new THREE.Vector3(RACK_SLOTS[i][0], 0.005, RACK_SLOTS[i][1]);
      gear.spinner.position.copy(slot);
      this.rack.add(gear.spinner);
      const pin = new THREE.Mesh(new THREE.CylinderGeometry(0.06, 0.06, 0.2, 12), metal);
      pin.position.set(slot.x, 0.1, slot.z);
      this.rack.add(pin);
      this.loose.push({ ...gear, size, material, slot, peg: null, moving: false });
    });

    // Inner case: holds the token, bolted by a rod from each latch hub.
    const caseWidth = CASE.x1 - CASE.x0;
    const caseDepth = CASE.z1 - CASE.z0;
    const caseX = (CASE.x0 + CASE.x1) / 2;
    const caseZ = (CASE.z0 + CASE.z1) / 2;
    const wall = 0.08;
    for (const [w, d, x, z] of [
      [caseWidth, wall, caseX, CASE.z0 + wall / 2],
      [caseWidth, wall, caseX, CASE.z1 - wall / 2],
      [wall, caseDepth, CASE.x0 + wall / 2, caseZ],
      [wall, caseDepth, CASE.x1 - wall / 2, caseZ],
    ]) {
      const slab = new THREE.Mesh(new THREE.BoxGeometry(w, CASE.height, d), metal);
      slab.position.set(x, CASE.height / 2, z);
      slab.castShadow = true;
      this.root.add(slab);
    }
    const inner = new THREE.Mesh(
      new THREE.BoxGeometry(caseWidth - wall * 2, 0.02, caseDepth - wall * 2),
      new THREE.MeshStandardMaterial({ color: 0x0b0b0c, roughness: 0.8 }),
    );
    inner.position.set(caseX, 0.02, caseZ);
    this.root.add(inner);

    // Lid hinged on the back edge.
    this.caseLid.position.set(caseX, CASE.height, CASE.z0);
    this.root.add(this.caseLid);
    const lidPlate = new THREE.Mesh(new THREE.BoxGeometry(caseWidth, 0.06, caseDepth), dark);
    lidPlate.position.set(0, 0.03, caseDepth / 2);
    lidPlate.castShadow = true;
    this.caseLid.add(lidPlate);
    const seam = new THREE.Mesh(new THREE.PlaneGeometry(caseWidth * 0.5, 0.025), amber);
    seam.rotation.x = -Math.PI / 2;
    seam.position.set(0, 0.062, caseDepth / 2);
    this.caseLid.add(seam);

    // A rod from each latch hub into the nearest case wall; it slides back
    // as its latch turns open.
    const rodY = GEAR_LIFT + GEAR_THICKNESS + 0.08;
    for (const { id } of LATCHES) {
      const [lx, lz] = FIXED[id].at;
      const nx = THREE.MathUtils.clamp(lx, CASE.x0, CASE.x1);
      const nz = THREE.MathUtils.clamp(lz, CASE.z0, CASE.z1);
      const dir = new THREE.Vector3(nx - lx, 0, nz - lz);
      const reach = dir.length() + 0.15;
      dir.normalize();
      const mesh = new THREE.Mesh(new THREE.CylinderGeometry(0.045, 0.045, reach, 12), metal);
      mesh.quaternion.setFromUnitVectors(new THREE.Vector3(0, 1, 0), dir);
      const rest = new THREE.Vector3(lx, rodY, lz).addScaledVector(dir, reach / 2);
      mesh.position.copy(rest);
      this.root.add(mesh);
      this.bolts[id] = { mesh, rest, out: rest.clone().addScaledVector(dir, -BOLT_TRAVEL) };
    }

    const token = createToken();
    this.token = token.group;
    this.tokenGlow = token.glow;
    this.tokenGlow.emissiveIntensity = 0.5;
    this.token.position.set(caseX, 0.42, caseZ);
    // Face tipped up toward the camera that looks down into the box; it
    // turns in its own plane so the face always shows.
    this.token.rotation.x = -Math.PI / 3;
    this.root.add(this.token);
    // Soft halo around the token; additive, so it reads as light.
    const haloCanvas = document.createElement("canvas");
    haloCanvas.width = haloCanvas.height = 128;
    const haloCtx = haloCanvas.getContext("2d");
    const gradient = haloCtx.createRadialGradient(64, 64, 0, 64, 64, 64);
    gradient.addColorStop(0, "rgba(90, 150, 255, 0.7)");
    gradient.addColorStop(0.35, "rgba(60, 120, 255, 0.35)");
    gradient.addColorStop(1, "rgba(40, 90, 255, 0)");
    haloCtx.fillStyle = gradient;
    haloCtx.fillRect(0, 0, 128, 128);
    this.halo = new THREE.Sprite(
      new THREE.SpriteMaterial({
        map: new THREE.CanvasTexture(haloCanvas),
        blending: THREE.AdditiveBlending,
        depthWrite: false,
        transparent: true,
        opacity: 0,
      }),
    );
    this.halo.scale.setScalar(2.2);
    this.token.add(this.halo);
    this.tokenHit = new THREE.Mesh(
      new THREE.SphereGeometry(0.6, 12, 8),
      new THREE.MeshBasicMaterial({ transparent: true, opacity: 0, depthWrite: false }),
    );
    this.token.add(this.tokenHit);
    this.tokenLight.position.set(caseX, 0.6, caseZ);
    this.root.add(this.tokenLight);

    // The real prize waits hidden under the case floor until the very end.
    const prize = createPrizeGem();
    this.prize = prize.group;
    this.sparkles = prize.sparkles;
    this.prize.position.set(caseX, 0.2, caseZ);
    this.prize.visible = false;
    this.root.add(this.prize);
    this.prizeLight.position.set(caseX, 1.2, caseZ);
    this.root.add(this.prizeLight);

    this.canvas.addEventListener("pointerdown", this.handlePointerDown);
    this.canvas.addEventListener("pointermove", this.handlePointerMove);
    this.canvas.addEventListener("pointerup", this.handlePointerUp);
    this.canvas.addEventListener("pointercancel", this.handlePointerUp);
  }

  // Everything on the floor that can turn: fixed gears and fitted ones.
  private placed() {
    const list: { key: FixedId | Loose; at: Vec; r: number }[] = (Object.keys(FIXED) as FixedId[]).map(
      (id) => ({ key: id, at: FIXED[id].at, r: FIXED[id].r }),
    );
    for (const gear of this.loose) {
      if (gear.peg !== null && !gear.moving) list.push({ key: gear, at: PEGS[gear.peg], r: SIZE[gear.size] });
    }
    return list;
  }

  // Gears turning with the driver, each with its sense relative to it, or
  // null if they jam (an odd ring cannot turn).
  private chain() {
    const nodes = this.placed();
    const sense = new Map<FixedId | Loose, number>([["D", 1]]);
    const queue = [nodes[0]];
    while (queue.length) {
      const g = queue.shift();
      for (const other of nodes) {
        if (other === g || contact(g.at, g.r, other.at, other.r) !== 1) continue;
        const want = -sense.get(g.key);
        if (!sense.has(other.key)) {
          sense.set(other.key, want);
          queue.push(other);
        } else if (sense.get(other.key) !== want) {
          return null;
        }
      }
    }
    return sense;
  }

  private gearOf(key: FixedId | Loose) {
    return typeof key === "string" ? this.fixed[key] : key;
  }

  private radiusOf(key: FixedId | Loose) {
    return typeof key === "string" ? FIXED[key].r : SIZE[key.size];
  }

  // `turn` < 0: the driver goes clockwise seen from above.
  private drive(turn: number) {
    const chain = this.chain();
    if (!chain) {
      if (!this.jammed) {
        this.jammed = true;
        this.shake(this.fixed.D.spinner, 0.04);
      }
      return;
    }

    // A latch turned the wrong way stops the whole train at its stop.
    let stopped: "L1" | "L2" | null = null;
    for (const { id, open } of LATCHES) {
      const sense = chain.get(id);
      if (sense === undefined) continue;
      const rate = sense * open * (FIXED.D.r / FIXED[id].r);
      if (this.progress[id] + turn * rate < LATCH_STOP) {
        turn = (LATCH_STOP - this.progress[id]) / rate;
        stopped = id;
      }
    }
    if (stopped && !this.atStop) this.shake(this.fixed[stopped].spinner, 0.05);
    this.atStop = stopped !== null;

    for (const [key, sense] of chain) {
      this.gearOf(key).spinner.rotation.y += turn * sense * (FIXED.D.r / this.radiusOf(key));
    }
    for (const { id, open } of LATCHES) {
      const sense = chain.get(id);
      if (sense === undefined) continue;
      this.progress[id] += turn * sense * open * (FIXED.D.r / FIXED[id].r);
      this.setBolt(id);
    }

    if (LATCHES.every(({ id }) => this.progress[id] >= LATCH_OPEN)) this.solve();
  }

  private setBolt(id: "L1" | "L2") {
    const bolt = this.bolts[id];
    const t = THREE.MathUtils.clamp(this.progress[id] / LATCH_OPEN, 0, 1);
    bolt.mesh.position.lerpVectors(bolt.rest, bolt.out, t);
  }

  // Let go, and the springs turn both latches back shut.
  private springBack() {
    for (const { id, open } of LATCHES) {
      const progress = this.progress[id];
      if (progress === 0) continue;
      const state = { p: progress };
      const spinner = this.fixed[id].spinner;
      const base = spinner.rotation.y - progress * open;
      gsap.to(state, {
        p: 0,
        duration: 0.35,
        ease: "power2.in",
        onUpdate: () => {
          this.progress[id] = state.p;
          spinner.rotation.y = base + state.p * open;
          this.setBolt(id);
        },
      });
    }
  }

  private shake(object: THREE.Object3D, amount: number) {
    const base = object.rotation.y;
    gsap
      .timeline()
      .to(object.rotation, { y: base + amount, duration: 0.04 })
      .to(object.rotation, { y: base - amount, duration: 0.06 })
      .to(object.rotation, { y: base, duration: 0.08 });
  }

  private hold(gear: Loose | null) {
    if (this.held) {
      this.held.material.emissiveIntensity = 0;
      gsap.to(this.held.spinner.position, { y: this.held.slot.y, duration: 0.15 });
    }
    this.held = gear;
    if (gear) {
      gear.material.emissive.setHex(PALETTE.amber);
      gear.material.emissiveIntensity = 0.35;
      gsap.to(gear.spinner.position, { y: gear.slot.y + 0.12, duration: 0.15 });
    }
  }

  // Fly a gear between the rack and a peg, keeping it where it is on screen
  // while it changes parent.
  private move(gear: Loose, peg: number | null) {
    gsap.killTweensOf(gear.spinner.position);
    gear.moving = true;
    gear.peg = peg;
    const toPeg = peg !== null;
    (toPeg ? this.root : this.rack).attach(gear.spinner);
    const target = toPeg ? new THREE.Vector3(PEGS[peg][0], GEAR_LIFT, PEGS[peg][1]) : gear.slot;
    const lift = toPeg ? 0.6 : 0.3;
    gsap
      .timeline({
        onComplete: () => {
          gear.moving = false;
        },
      })
      .to(gear.spinner.rotation, { x: 0, z: 0, duration: 0.45, ease: "power2.inOut" }, 0)
      .to(gear.spinner.position, { x: target.x, z: target.z, duration: 0.45, ease: "power2.inOut" }, 0)
      .to(gear.spinner.position, { y: Math.max(gear.spinner.position.y, target.y) + lift, duration: 0.2, ease: "power1.out" }, 0)
      .to(gear.spinner.position, { y: target.y, duration: 0.25, ease: "power2.in" }, 0.2);
  }

  private tryFit(gear: Loose, peg: number) {
    const at = PEGS[peg];
    const r = SIZE[gear.size];
    const clash =
      !fitsBox(at, r) ||
      this.loose.some((o) => o !== gear && o.peg !== null && contact(at, r, PEGS[o.peg], SIZE[o.size]) === -1);
    if (clash) {
      // Will not go in: it is too big for the gap.
      this.shake(gear.spinner, 0.15);
      return;
    }
    gear.material.emissiveIntensity = 0;
    this.held = null;
    this.move(gear, peg);
  }

  private solve() {
    this.solved = true;
    this.dragId = null;
    this.canvas.style.cursor = "default";
    gsap
      .timeline()
      .to(this.caseLid.rotation, { x: -1.9, duration: 0.6, ease: "back.out(2)" }, "+=0.3")
      .to(this.tokenLight, { intensity: 22, duration: 1.6, ease: "power1.in" }, "<")
      // Up past the rim of the box, glowing brighter as it rises.
      .to(this.token.position, { y: 2.7, duration: 2.4, ease: "power2.out" }, "<0.2")
      .to(this.tokenGlow, { emissiveIntensity: 0.9, duration: 2.4 }, "<")
      .to(this.halo.material, { opacity: 1, duration: 2.4 }, "<")
      .to(this.token.rotation, { z: Math.PI * 2, duration: 2.4, ease: "power1.inOut" }, "<")
      .to(this.tokenLight.position, { y: 2.6, duration: 2.4 }, "<")
      .call(() => this.options.onSolved?.(), [], "-=1.2")
      .call(() => {
        // Hovers over the box until taken (repeating tweens keep rendering).
        this.tokenReady = true;
        this.tokenHover = [
          gsap.to(this.token.position, { y: 2.85, duration: 1.6, yoyo: true, repeat: -1, ease: "sine.inOut" }),
          gsap.to(this.token.rotation, { z: `+=${Math.PI * 2}`, duration: 6, repeat: -1, ease: "none" }),
        ];
      });
  }

  // The ending: out of the empty case rises the real prize, turning, with
  // light glinting off it.
  public revealPrize() {
    this.prize.visible = true;
    gsap
      .timeline()
      .to(this.prizeLight, { intensity: 30, duration: 1.2 })
      .to(this.prize.position, { y: 4.1, duration: 2.6, ease: "power2.out" }, "<")
      .to(this.prize.rotation, { y: Math.PI * 2, duration: 8, ease: "none", repeat: -1 }, "<")
      .to(this.prizeLight.position, { y: 4.6, duration: 2.6, ease: "power2.out" }, "<");
    this.sparkles.forEach((sparkle, i) => {
      gsap.to(sparkle.material, {
        opacity: 1,
        duration: 0.35,
        yoyo: true,
        repeat: -1,
        repeatDelay: 0.9 + i * 0.37,
        delay: 1 + i * 0.45,
        ease: "power2.inOut",
      });
    });
  }

  // Up and away into the inventory; its light leaves with it.
  private takeToken() {
    this.tokenReady = false;
    this.canvas.style.cursor = "default";
    this.tokenHover.forEach((t) => t.kill());
    gsap
      .timeline()
      .to(this.token.position, { y: 4.2, duration: 0.6, ease: "power2.in" })
      .to(this.token.scale, { x: 0.01, y: 0.01, z: 0.01, duration: 0.6, ease: "power2.in" }, "<")
      .to(this.tokenLight, { intensity: 0, duration: 0.6 }, "<")
      .call(() => {
        this.token.visible = false;
        this.options.onTokenTaken?.();
      });
  }

  private hits(object: THREE.Object3D, event: PointerEvent) {
    return pickObject(object, this.camera, this.canvas, event.clientX, event.clientY);
  }

  private looseAt(event: PointerEvent) {
    return this.loose.find((g) => !g.moving && this.hits(g.body, event));
  }

  private freePegAt(event: PointerEvent) {
    return this.pegHits.findIndex(
      (hit, i) => this.hits(hit, event) && !this.loose.some((g) => g.peg === i),
    );
  }

  private pointerAngle(event: PointerEvent) {
    const center = screenCenter(this.fixed.D.spinner, this.camera, this.canvas);
    return Math.atan2(event.clientY - center.y, event.clientX - center.x);
  }

  private handlePointerDown = (event: PointerEvent) => {
    if (this.enabled && this.tokenReady && this.hits(this.tokenHit, event)) {
      this.takeToken();
      return;
    }
    if (!this.enabled || this.solved || this.dragId !== null) return;
    if (this.hits(this.fixed.D.body, event)) {
      this.dragId = event.pointerId;
      this.lastAngle = this.pointerAngle(event);
      this.jammed = false;
      this.canvas.setPointerCapture(event.pointerId);
      return;
    }
    const gear = this.looseAt(event);
    if (gear) {
      if (gear.peg !== null) this.move(gear, null);
      else this.hold(this.held === gear ? null : gear);
      return;
    }
    if (!this.held) return;
    const peg = this.freePegAt(event);
    if (peg >= 0) this.tryFit(this.held, peg);
  };

  private handlePointerMove = (event: PointerEvent) => {
    if (this.enabled && this.tokenReady) {
      this.canvas.style.cursor = this.hits(this.tokenHit, event) ? "pointer" : "default";
      return;
    }
    if (!this.enabled || this.solved) return;
    if (event.pointerId === this.dragId) {
      const angle = this.pointerAngle(event);
      const delta = Math.atan2(Math.sin(angle - this.lastAngle), Math.cos(angle - this.lastAngle));
      this.lastAngle = angle;
      // Screen y points down: a clockwise drag is a positive delta, a
      // negative turn. The pawl stops the other way.
      if (delta > 0) this.drive(-delta);
      return;
    }
    const over =
      this.hits(this.fixed.D.body, event) ||
      this.looseAt(event) !== undefined ||
      (this.held !== null && this.freePegAt(event) >= 0);
    this.canvas.style.cursor = over ? "pointer" : "default";
  };

  private handlePointerUp = (event: PointerEvent) => {
    if (event.pointerId !== this.dragId) return;
    this.dragId = null;
    if (this.canvas.hasPointerCapture(event.pointerId)) {
      this.canvas.releasePointerCapture(event.pointerId);
    }
    if (!this.solved) this.springBack();
  };

  public setEnabled(enabled: boolean) {
    this.enabled = enabled;
    if (!enabled) {
      this.dragId = null;
      this.hold(null);
    }
  }

  public dispose() {
    this.canvas.removeEventListener("pointerdown", this.handlePointerDown);
    this.canvas.removeEventListener("pointermove", this.handlePointerMove);
    this.canvas.removeEventListener("pointerup", this.handlePointerUp);
    this.canvas.removeEventListener("pointercancel", this.handlePointerUp);
    gsap.killTweensOf([
      this.caseLid.rotation,
      this.token.position,
      this.token.rotation,
      this.token.scale,
      this.tokenGlow,
      this.prize.position,
      this.prize.rotation,
      this.prizeLight,
      ...this.sparkles.map((s) => s.material),
      this.halo.material,
      this.tokenLight,
      this.tokenLight.position,
      ...Object.values(this.fixed).map((g) => g.spinner.rotation),
      ...this.loose.flatMap((g) => [g.spinner.rotation, g.spinner.position]),
    ]);
    this.rack.removeFromParent();
    disposeTree(this.rack);
    disposeTree(this.root);
  }
}

// Inlay for the box's back wall, in white: meshing gears turn opposite
// ways; three in a ring jam. Pictures only.
export function createGearClueTexture() {
  const canvas = document.createElement("canvas");
  canvas.width = 1024;
  canvas.height = 512;
  const ctx = canvas.getContext("2d");
  if (!ctx) throw new Error("Canvas 2D context is unavailable.");
  ctx.fillStyle = css(PALETTE.walnut);
  ctx.fillRect(0, 0, 1024, 512);
  ctx.strokeStyle = "#f4efe6";
  ctx.fillStyle = "#f4efe6";
  ctx.lineCap = "round";
  ctx.lineJoin = "round";

  const gear = (x: number, y: number, r: number) => {
    const teeth = Math.round(r / 7);
    ctx.lineWidth = 6;
    ctx.beginPath();
    for (let i = 0; i < teeth * 2; i++) {
      const a = (i / (teeth * 2)) * Math.PI * 2;
      const rr = i % 2 ? r - 10 : r + 6;
      ctx.lineTo(x + Math.cos(a) * rr, y + Math.sin(a) * rr);
    }
    ctx.closePath();
    ctx.stroke();
    ctx.beginPath();
    ctx.arc(x, y, 8, 0, Math.PI * 2);
    ctx.fill();
  };
  // Canvas angles run clockwise (y down).
  const arrow = (x: number, y: number, r: number, clockwise: boolean) => {
    const start = -Math.PI * 0.75;
    const sweep = Math.PI * 1.1 * (clockwise ? 1 : -1);
    const end = start + sweep;
    ctx.lineWidth = 7;
    ctx.beginPath();
    ctx.arc(x, y, r, start, end, !clockwise);
    ctx.stroke();
    const tangent = end + (clockwise ? Math.PI / 2 : -Math.PI / 2);
    const hx = x + Math.cos(end) * r;
    const hy = y + Math.sin(end) * r;
    ctx.beginPath();
    ctx.moveTo(hx + Math.cos(tangent) * 22, hy + Math.sin(tangent) * 22);
    ctx.lineTo(hx + Math.cos(tangent + 2.4) * 18, hy + Math.sin(tangent + 2.4) * 18);
    ctx.lineTo(hx + Math.cos(tangent - 2.4) * 18, hy + Math.sin(tangent - 2.4) * 18);
    ctx.closePath();
    ctx.fill();
  };

  // Left: two gears in mesh, opposite ways.
  gear(150, 256, 92);
  arrow(150, 256, 50, true);
  gear(150 + 92 + 82 - 4, 256, 82);
  arrow(320, 256, 44, false);

  // Divider.
  ctx.lineWidth = 4;
  ctx.beginPath();
  ctx.moveTo(512, 90);
  ctx.lineTo(512, 422);
  ctx.stroke();

  // Right: three gears in a ring, crossed out.
  const r = 70;
  const cx = 770;
  const cy = 270;
  const d = r * 2 - 4;
  const ring: [number, number][] = [
    [cx - d / 2, cy + d * 0.29],
    [cx + d / 2, cy + d * 0.29],
    [cx, cy - d * 0.58],
  ];
  for (const [x, y] of ring) gear(x, y, r);
  ctx.lineWidth = 14;
  ctx.beginPath();
  ctx.moveTo(cx - 200, cy - 190);
  ctx.lineTo(cx + 200, cy + 190);
  ctx.moveTo(cx + 200, cy - 190);
  ctx.lineTo(cx - 200, cy + 190);
  ctx.stroke();

  const texture = new THREE.CanvasTexture(canvas);
  texture.colorSpace = THREE.SRGBColorSpace;
  texture.anisotropy = 8;
  return texture;
}
